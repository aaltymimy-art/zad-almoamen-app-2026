create table if not exists public.members (
  id bigint generated by default as identity primary key,
  full_name text not null check (char_length(full_name) between 2 and 120),
  age integer not null check (age between 1 and 120),
  phone text not null check (char_length(phone) between 5 and 30),
  relation text not null check (relation in (
    'الرابطة 1','الرابطة 2','الرابطة 3','الرابطة 4','الرابطة 5',
    'الرابطة 6','الرابطة 7'
  )),
  role_in_relation text not null check (char_length(role_in_relation) between 1 and 1000),
  created_at timestamptz not null default now()
);

create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.members enable row level security;
alter table public.admins enable row level security;

-- يسمح للزائر بإرسال تسجيل جديد فقط، ولا يسمح له بقراءة أو تعديل السجلات.
drop policy if exists "public can submit registrations" on public.members;
create policy "public can submit registrations"
on public.members for insert to anon, authenticated
with check (true);

-- صلاحيات القراءة والتعديل والحذف للمديرين المسجلين في جدول admins فقط.
drop policy if exists "admins can read members" on public.members;
create policy "admins can read members"
on public.members for select to authenticated
using (exists (select 1 from public.admins a where a.user_id = auth.uid()));

drop policy if exists "admins can update members" on public.members;
create policy "admins can update members"
on public.members for update to authenticated
using (exists (select 1 from public.admins a where a.user_id = auth.uid()))
with check (exists (select 1 from public.admins a where a.user_id = auth.uid()));

drop policy if exists "admins can delete members" on public.members;
create policy "admins can delete members"
on public.members for delete to authenticated
using (exists (select 1 from public.admins a where a.user_id = auth.uid()));

-- المدير يستطيع رؤية سجل صلاحيات الإدارة الخاص به فقط.
drop policy if exists "admins can view own admin row" on public.admins;
create policy "admins can view own admin row"
on public.admins for select to authenticated
using (user_id = auth.uid());

-- لا توجد سياسة تسجيل عامة أو تعديل عام لجدول admins.
